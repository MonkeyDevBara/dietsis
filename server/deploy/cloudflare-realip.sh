#!/usr/bin/env bash
# Writes /etc/nginx/snippets/dietsis-cloudflare.conf so nginx trusts CF-Connecting-IP ONLY from Cloudflare's
# published address ranges. Run as root when the domain is proxied by Cloudflare; re-run now and then
# (ranges change rarely), then: nginx -t && systemctl reload nginx
set -euo pipefail
OUT=/etc/nginx/snippets/dietsis-cloudflare.conf
TMP="$(mktemp)"
{
  echo "# Generated by deploy/cloudflare-realip.sh on $(date -u +%F). Do not edit."
  for list in ips-v4 ips-v6; do
    curl -fsS --max-time 15 "https://www.cloudflare.com/$list" | while read -r cidr; do
      [[ "$cidr" =~ ^[0-9a-fA-F:./]+$ ]] && echo "set_real_ip_from $cidr;"
    done
  done
  echo "real_ip_header CF-Connecting-IP;"
} > "$TMP"
[ "$(grep -c '^set_real_ip_from' "$TMP")" -ge 10 ] || { echo "suspiciously few ranges, keeping the old file" >&2; rm -f "$TMP"; exit 1; }
install -m 0644 "$TMP" "$OUT"; rm -f "$TMP"
echo "wrote $OUT ($(grep -c '^set_real_ip_from' "$OUT") ranges)"
